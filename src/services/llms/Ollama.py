### Core modules ###
from datetime import datetime
from pathlib import Path
from ollama import (
    ChatResponse,
    Client
)
from dotenv import dotenv_values


### Type hints ###
from typing import Any


### Internal modules ###
from .LLMBase import LLMBase
from .OllamaPullManager import OllamaPullManager



class Ollama(LLMBase):
    def __init__(
        self,
        llm_name:       str = "llama3.2",
        container_name: str = str(
            dotenv_values(
                # Looks complex but essentially, it means to read `.env` file
                # from project root directory
                dotenv_path=Path(__file__).resolve(strict=True).parent.parent.parent.parent.joinpath(".env"),
                encoding="utf-8"
            ).get(
                "OLLAMA_SERVICE_NAME",
                "cosmic-ollama"
            )
        ),
        local_port:     int = 11434,
        **kwargs
    ) -> None:
        """
        LLMs using the official Ollama container.

        Args:
            llm_name (str, optional):
                Ollama supported LLMs available at https://ollama.com/library.

            container_name (str, optional):
                Name of the Ollama container defined in environment file. Fallback
                to "cosmic-ollama" if not found.

            local_port (int, optional):
                Local port for the Ollama container. Defaults to 11434.
        """
        model_name = llm_name.replace("ollama:", "")
        super().__init__(llm_name=model_name, **kwargs)
        self._tag_model() # adds :latest if not present
        self.ollama_client = self._set_local_client(
            container_name=container_name,
            port=local_port
        ) # local client instance
        self.ollama_pull_manager = OllamaPullManager(
            model_name=self.llm_name,
            mode="stochastic",
            interventions=[85, 95],
            max_retries=3,
            fall_back_interval=60,
            ollama_client=self.ollama_client
        )
        self._check_availability()

        return None


    def _tag_model(self) -> None:
        if ":" not in self.llm_name:
            self.llm_name = f"{self.llm_name}:latest"

        return None


    def _set_local_client(
        self,
        container_name: str,
        port:           int
    ) -> Client:
        """
        Set the local client for the Ollama container.

        Args:
            container_name (str): Name of the Ollama container.
        """
        client: Client = Client(
            host = f"http://{container_name}:{port}",
            headers = {"Content-Type": "application/json"}
        )

        return client


    def _check_availability(self) -> None:
        """
        Check if the Ollama container is available and the specified model is available.
        Raises an exception if the container or model is not available.
        """
        self.ollama_pull_manager.pull_model()

        return None


    def __call__(
        self,
        question:           str,
        context:            str | dict[str, Any]            = {},
        service_name:       str                             = "",
        history_messages:   list[dict[str, str]] | None     = None
    ) -> tuple[str, str, datetime, int, int]:
        """
        Process the question and generate a response using Ollama.

        Args:
            question (str):
                user question in string.

            context (str | dict[str, Any], optional):
                context for the question. Defaults to {}.

            service_name (str, optional):
                name of the service. Defaults to "".

        Returns:
            response (str):
                LLM response.

            raw_response (str):
                LLM raw response without truncations.

            response_timestamp (datetime):
                LLM response timestamp. Converted to datetime type to fit in with
                Pydantic AwareDateTime type.

            input_token (int):
                amount of input tokens captured by Ollama when processing each
                query received from QA.

            output_token (int):
                amount of output tokens generated by Ollama when processing each
                query received from QA.
        """
        # print(
        #     set_color(
        #         status="info",
        #         information=f"Ollama models used: {self.llm_name}"
        #     )
        # )
        # Generate user prompt with question and context
        user_prompt: str = self.user_prompter( # pyright: ignore[reportCallIssue]
            question,
            context=context
        )

        # Combine system prompt, prior turns and user prompt.
        combined_prompt: list[dict[str, str]] = self.system_prompter(
            user_prompt,
            context=context,
            service=service_name, # pyright: ignore[reportCallIssue]
            history_messages=history_messages
        )

        # Chat
        chat_response: ChatResponse = self.ollama_client.chat(
            model=self.llm_name,
            messages=combined_prompt,
        )
        raw_response:       str         = chat_response["message"]["content"]
        response_timestamp: datetime    = datetime.fromisoformat(chat_response["created_at"])
        input_token:        int         = chat_response["prompt_eval_count"]
        output_token:       int         = chat_response["eval_count"]

        # Apply truncation if enabled
        response: str = (
            self.truncate_response(raw_response)
            if   (self.is_truncate_response)
            else (raw_response)
        )

        return (
            response,
            raw_response,
            response_timestamp,
            input_token,
            output_token
        )


    def quit(self) -> None:
        """
        Clean up any resources. No specific cleanup needed for API-based implementation.
        """
        # No resources to clean up for REST API implementation
        pass
